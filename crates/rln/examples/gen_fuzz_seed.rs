//! Regenerates the genuine-proof fixture used by
//! `crates/rln/tests/data/seed_proof.bin` (checked every gate run by
//! `the_seed_proof_fixture_still_parses_and_verifies`) and
//! `crates/core/fuzz/fuzz_targets/rln_verify.rs` (which splices fuzzer
//! bytes into it). Run with:
//!
//!     cargo run -p novachannel-rln --release --example gen_fuzz_seed
//!
//! It writes `seed_proof.bin` and prints the public inputs for
//! `seed_public_inputs.txt` and the fuzz target's `const` block; all three
//! must be regenerated together. Prove in `--release` (see `lib.rs`, "Run
//! tests with `--release`"): the debug-only winterfell check can trip on
//! this AIR. `cargo fuzz build` keeps debug assertions even in release,
//! which is why the fuzz target embeds a proof made here instead of proving
//! itself.
use novachannel_rln::air::{self, Witness};
use novachannel_rln::merkle::MerkleTree;
use novachannel_rln::permutation::{compress2, Params};
use novachannel_rln::{bytes_to_field, epoch_field, Identity};
use winterfell::math::fields::f64::BaseElement;
use winterfell::Prover;

fn field_literal(name: &str, v: BaseElement) {
    println!("const {name}: u64 = {};", v.as_int());
}

fn main() {
    let params = Params::new();
    let identity = Identity::generate();
    let leaves = vec![identity.commitment(&params)];
    let tree = MerkleTree::new(air::DEPTH, &leaves);
    let path = tree.path(0);
    let witness = Witness {
        sk: identity.sk,
        path,
    };

    let epoch = epoch_field(1);
    let x = bytes_to_field(b"rln-verify-fuzz-genuine-input");
    let a1 = compress2(&params, identity.sk, epoch);
    let y = identity.sk + a1 * x;

    let trace = air::build_trace(&params, &witness, epoch, x);
    let root = trace.get(0, air::root_row(air::DEPTH));
    let pub_inputs = air::PublicInputs {
        root,
        epoch,
        x,
        y,
        nullifier: a1,
    };

    let prover = air::RlnProver::new(air::default_proof_options(), pub_inputs.clone());
    let proof = prover.prove(trace).expect("proof generation failed");
    let bytes = proof.to_bytes();

    let out = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/data/seed_proof.bin");
    std::fs::write(out, &bytes).expect("write the seed proof fixture");

    println!("// Generated by `cargo run -p novachannel-rln --release --example gen_fuzz_seed`.");
    println!("// Wrote {} bytes to {out}", bytes.len());
    println!("// Copy these into crates/rln/tests/data/seed_public_inputs.txt (one per line,");
    println!("// in this order) and into crates/core/fuzz/fuzz_targets/rln_verify.rs.");
    field_literal("ROOT", pub_inputs.root);
    field_literal("EPOCH", pub_inputs.epoch);
    field_literal("X", pub_inputs.x);
    field_literal("Y", pub_inputs.y);
    field_literal("NULLIFIER", pub_inputs.nullifier);
}
